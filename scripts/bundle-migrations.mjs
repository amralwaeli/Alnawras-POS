#!/usr/bin/env node
/**
 * Copies every supabase/migrations/NNNN_*.sql into the setup-onetime-tenant Edge Function,
 * which runs them on a new one-time customer's project. Run after adding a migration,
 * then redeploy the function:
 *   node scripts/bundle-migrations.mjs
 *   npx supabase functions deploy setup-onetime-tenant --project-ref uasnihapkcrgibnpqdyi --use-api
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(ROOT, 'supabase', 'migrations');
const files = readdirSync(dir).filter((f) => /^\d{4}_.*\.sql$/.test(f)).sort();
const list = files.map((name) => ({ name, sql: readFileSync(path.join(dir, name), 'utf8') }));
const out = path.join(ROOT, 'supabase', 'functions', 'setup-onetime-tenant', 'migrations.ts');
writeFileSync(out, '// Generated by scripts/bundle-migrations.mjs — do not edit.\n'
  + `export const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(list, null, 0)};\n`);
console.log(`Bundled ${list.length} migrations (${list[list.length - 1]?.name}) into ${path.relative(ROOT, out)}`);
